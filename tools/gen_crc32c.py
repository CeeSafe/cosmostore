#!/usr/bin/env python3
"""Generates src/storage/checksums/crc32c_tables.cee: CRC32C (Castagnoli) slicing-by-8 tables."""
import pathlib
POLY = 0x82F63B78
t = [[0] * 256 for _ in range(8)]
for i in range(256):
    c = i
    for _ in range(8):
        c = (c >> 1) ^ POLY if c & 1 else c >> 1
    t[0][i] = c
for k in range(1, 8):
    for i in range(256):
        t[k][i] = (t[k - 1][i] >> 8) ^ t[0][t[k - 1][i] & 0xFF]
flat = [x for row in t for x in row]
lines = ["// Generated by tools/gen_crc32c.py; do not edit.", "",
         "/// CRC32C slicing-by-8 tables: table k at [k * 256 .. k * 256 + 256].",
         "const CRC32C_TABLE: [u32; 2048] = ["]
for i in range(0, len(flat), 8):
    lines.append("    " + ", ".join("0x%08X" % v for v in flat[i:i + 8]) + ",")
lines.append("];")
out = pathlib.Path(__file__).resolve().parent.parent / "src/storage/checksums/crc32c_tables.cee"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n")
